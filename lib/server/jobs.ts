// Scheduled work, run by `npm run worker` (every minute) or POST /api/cron/tick.
//  1. Publish posts whose scheduledAt has passed (claimed with a lock so parallel workers cannot double-publish).
//  2. Generate the daily AI drafts for companies with auto-generation enabled (once per company-local day).

import { db } from "./db";
import { logActivity, notify } from "./audit";
import { publishVariant } from "./publisher";
import { generateDraft, type BrandContext } from "./ai";
import { findProhibitedWords, PLATFORMS, type Platform } from "@/lib/domain";
import { addDays, localDate, zonedToUtc } from "@/lib/tz";

const LOCK_STALE_MS = 10 * 60_000;

export type TickReport = { published: number; failed: number; generated: number; generationErrors: number };

export async function runTick(now = new Date()): Promise<TickReport> {
  const report: TickReport = { published: 0, failed: 0, generated: 0, generationErrors: 0 };
  await publishDue(now, report);
  await generateDaily(now, report);
  return report;
}

async function publishDue(now: Date, report: TickReport) {
  const due = await db.post.findMany({
    where: {
      status: "scheduled",
      scheduledAt: { lte: now },
      OR: [{ publishLockedAt: null }, { publishLockedAt: { lt: new Date(now.getTime() - LOCK_STALE_MS) } }],
    },
    select: { id: true, version: true },
    take: 50,
    orderBy: { scheduledAt: "asc" },
  });

  for (const candidate of due) {
    const claim = await db.post.updateMany({
      where: { id: candidate.id, version: candidate.version, status: "scheduled" },
      data: { publishLockedAt: now, version: { increment: 1 } },
    });
    if (claim.count !== 1) continue;

    const post = await db.post.findUniqueOrThrow({ where: { id: candidate.id }, include: { variants: true } });
    const channels = await db.channelConnection.findMany({ where: { companyId: post.companyId } });
    const errors: string[] = [];
    let anySimulated = false;

    for (const v of post.variants) {
      if (v.publishStatus === "published") continue; // already delivered on an earlier attempt
      const outcome = await publishVariant(v, channels.find((c) => c.platform === v.platform));
      if (outcome.ok) {
        anySimulated ||= outcome.via === "simulated";
        await db.postVariant.update({
          where: { id: v.id },
          data: { publishStatus: "published", externalId: outcome.externalId, publishedAt: new Date(), publishError: null },
        });
      } else {
        errors.push(outcome.error);
        await db.postVariant.update({ where: { id: v.id }, data: { publishStatus: "failed", publishError: outcome.error } });
      }
    }
    if (!post.variants.length) errors.push("The post has no platform variants.");

    const success = errors.length === 0;
    await db.$transaction(async (tx) => {
      await tx.post.update({
        where: { id: post.id },
        data: {
          status: success ? "published" : "failed",
          publishedAt: success ? new Date() : null,
          publishedVia: success ? (anySimulated ? "simulated" : "live") : null,
          failureReason: success ? null : errors.join(" "),
          publishAttempts: { increment: 1 },
          lastAttemptAt: new Date(),
          publishLockedAt: null,
          version: { increment: 1 },
        },
      });
      await logActivity(tx, {
        companyId: post.companyId,
        actor: "system",
        entityType: "post",
        entityId: post.id,
        action: success ? (anySimulated ? "published (simulated)" : "published") : "publish failed",
        outcome: success ? "success" : "failure",
        detail: success ? undefined : errors.join(" "),
      });
      if (!success) {
        await notify(tx, {
          companyId: post.companyId,
          type: "publish_failed",
          message: `Publishing “${post.title}” failed: ${errors.join(" ")}`,
          postId: post.id,
          userIds: [post.createdById],
          roles: ["admin", "manager"],
        });
      }
    });
    if (success) report.published++;
    else report.failed++;
  }
}

/** Next local day's slots based on cadence and preferred times. */
function slotsFor(dateKey: string, times: string[], cadence: number, tz: string): Date[] {
  const list = (times.length ? times : ["09:00"]).slice().sort();
  const out: Date[] = [];
  for (let i = 0; i < Math.max(1, Math.min(cadence, 10)); i++) {
    const r = zonedToUtc(dateKey, list[i % list.length], tz);
    if (r.ok) out.push(r.value);
  }
  return out;
}

async function generateDaily(now: Date, report: TickReport) {
  const companies = await db.company.findMany({ where: { autoGenerateEnabled: true } });
  for (const company of companies) {
    const today = localDate(now, company.timezone);
    if (company.lastAutoGenerateDate === today) continue;
    // Claim the day so concurrent workers don't both generate.
    const claim = await db.company.updateMany({
      where: { id: company.id, OR: [{ lastAutoGenerateDate: null }, { lastAutoGenerateDate: { not: today } }] },
      data: { lastAutoGenerateDate: today },
    });
    if (claim.count !== 1) continue;
    const r = await generateForCompany(company.id, addDays(today, 1));
    report.generated += r.created;
    report.generationErrors += r.errors.length;
  }
}

/**
 * Generate `postingCadence` AI drafts for the given company-local date.
 * Drafts get a suggested time (not a schedule): a human must approve and schedule them.
 */
export async function generateForCompany(
  companyId: string,
  dateKey: string,
  triggeredBy?: { id: string; name: string },
): Promise<{ created: number; errors: string[] }> {
  const company = await db.company.findUniqueOrThrow({ where: { id: companyId } });
  const owner =
    (triggeredBy && (await db.user.findFirst({ where: { id: triggeredBy.id, companyId } }))) ||
    (await db.user.findFirst({ where: { companyId, role: "admin", status: "active" }, orderBy: { createdAt: "asc" } }));
  if (!owner) return { created: 0, errors: ["No active admin to own generated drafts."] };

  const brand: BrandContext = {
    name: company.name,
    industry: company.industry,
    brandVoice: company.brandVoice,
    targetAudience: company.targetAudience,
    campaignGoals: company.campaignGoals,
    prohibitedWords: company.prohibitedWords,
    hashtags: company.hashtags,
  };
  const themes = company.campaignGoals
    .split("\n")
    .map((t) => t.trim())
    .filter(Boolean);
  const platforms = (company.defaultPlatforms.length ? company.defaultPlatforms : ["linkedin"]) as Platform[];
  const slots = slotsFor(dateKey, company.preferredPublishTimes, company.postingCadence, company.timezone);
  const dayIndex = Math.floor(Date.parse(dateKey) / 86_400_000);
  const actor = triggeredBy ?? ("system" as const);
  const errors: string[] = [];
  let created = 0;

  for (let i = 0; i < slots.length; i++) {
    const theme = themes.length ? themes[(dayIndex + i) % themes.length] : "a helpful, on-brand update for our audience";
    const prompt = `Daily post for ${dateKey}. Theme: ${theme}`;
    const result = await generateDraft({ brand, prompt, platforms: platforms.filter((p) => PLATFORMS.includes(p)) });
    if (!result.ok) {
      errors.push(result.error);
      await db.aiGeneration.create({
        data: { companyId, createdById: triggeredBy?.id, prompt, modelRef: result.modelRef, succeeded: false, error: result.error },
      });
      await logActivity(db, { companyId, actor, entityType: "company", entityId: companyId, action: "daily AI generation failed", outcome: "failure", detail: result.error });
      continue;
    }
    const variants = platforms
      .filter((p) => result.draft.variants[p] !== undefined)
      .map((p) => ({ platform: p, copy: result.draft.variants[p] ?? "" }));
    const flagged = findProhibitedWords(variants.map((v) => v.copy).join(" "), company.prohibitedWords);
    const submit = company.autoSubmitForApproval;

    const post = await db.$transaction(async (tx) => {
      const p = await tx.post.create({
        data: {
          companyId,
          title: result.draft.title || `Daily post ${dateKey}`,
          masterCopy: result.draft.masterCopy,
          source: "auto",
          status: submit ? "pending_approval" : "draft",
          suggestedAt: slots[i],
          createdById: owner.id,
          variants: { create: variants },
          revisions: {
            create: { version: 1, title: result.draft.title, masterCopy: result.draft.masterCopy, variants, editorId: null },
          },
        },
      });
      await tx.aiGeneration.create({
        data: {
          companyId,
          postId: p.id,
          createdById: triggeredBy?.id,
          prompt,
          modelRef: result.modelRef,
          outputText: result.rawText.slice(0, 20000),
          succeeded: true,
        },
      });
      if (submit) await tx.approvalAction.create({ data: { postId: p.id, actorUserId: owner.id, action: "submit", comment: "Auto-generated daily draft" } });
      await logActivity(tx, {
        companyId,
        actor,
        entityType: "post",
        entityId: p.id,
        action: submit ? "auto-generated daily draft and submitted for approval" : "auto-generated daily draft",
        detail: [result.simulated ? "simulated AI output" : `model ${result.modelRef}`, flagged.length ? `prohibited words: ${flagged.join(", ")}` : ""]
          .filter(Boolean)
          .join("; "),
      });
      return p;
    });
    created++;
    await notify(db, {
      companyId,
      type: submit ? "approval_requested" : "draft_generated",
      message: `New AI daily draft for ${dateKey}: “${post.title}”${flagged.length ? ` (contains prohibited words: ${flagged.join(", ")})` : ""}.`,
      postId: post.id,
      roles: submit ? ["approver", "admin"] : ["creator", "manager", "admin"],
    });
  }

  if (errors.length) {
    await notify(db, {
      companyId,
      type: "generation_failed",
      message: `Daily AI generation for ${dateKey} had ${errors.length} failure(s): ${errors[0]}`,
      roles: ["admin", "manager"],
    });
  }
  return { created, errors };
}
