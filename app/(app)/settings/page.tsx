import Link from "next/link";
import { requireUser } from "@/lib/server/auth";
import { db } from "@/lib/server/db";
import { publisherMode } from "@/lib/server/publisher";
import { aiMode } from "@/lib/server/ai";
import { can, PLATFORMS } from "@/lib/domain";
import { formatDateTime, timeZones } from "@/lib/tz";
import { Card, CardHeader, PageHeader } from "@/components/ui";
import { cn } from "@/lib/utils";
import { ChannelCard, CompanyForm, CreateUserForm, GenerateNowForm, PostingForm, UserRow } from "./forms";

export const metadata = { title: "Settings" };

const TABS = [
  { key: "company", label: "Company & brand" },
  { key: "channels", label: "Channels" },
  { key: "posting", label: "Posting defaults" },
  { key: "users", label: "Users & roles" },
  { key: "activity", label: "Activity history" },
] as const;

export default async function SettingsPage({ searchParams }: { searchParams: Promise<{ tab?: string; welcome?: string }> }) {
  const user = await requireUser();
  const sp = await searchParams;
  const tab = TABS.find((t) => t.key === sp.tab)?.key ?? "company";
  const company = await db.company.findUniqueOrThrow({ where: { id: user.companyId } });
  const editable = can(user.role, "company.settings");
  const tz = company.timezone;

  return (
    <>
      <PageHeader title="Settings" description={editable ? "Company profile, channels, posting rules and team." : "You can view these settings. Ask an admin or manager to change them."} />
      {sp.welcome && (
        <p role="status" className="mb-4 rounded-lg border border-brand-200 bg-brand-50 px-4 py-3 text-sm text-brand-800">
          Workspace created. Next: describe your brand voice below so AI drafts sound like you, then add your team under “Users &amp; roles”.
        </p>
      )}
      <nav aria-label="Settings sections" className="mb-6 flex gap-1 overflow-x-auto border-b border-line">
        {TABS.map((t) => (
          <Link key={t.key} href={`/settings?tab=${t.key}`} aria-current={tab === t.key ? "page" : undefined} className={cn("-mb-px border-b-2 px-3 py-2 text-sm font-medium whitespace-nowrap", tab === t.key ? "border-brand-600 text-brand-800" : "border-transparent text-muted hover:text-ink")}>
            {t.label}
          </Link>
        ))}
      </nav>

      {tab === "company" && (
        <Card className="max-w-3xl">
          <CardHeader title="Company profile & brand voice" description="Used as context for every AI draft. Treated as data, not instructions." />
          <div className="p-5"><CompanyForm company={company} zones={timeZones()} disabled={!editable} /></div>
        </Card>
      )}

      {tab === "channels" && (
        <>
          <p className="mb-4 max-w-3xl rounded-lg border border-line bg-white px-4 py-3 text-sm text-muted">
            Live publishing integrations (OAuth with each network) are not configured in this version, so channels show as <strong>not connected</strong> and due posts fail with a clear reason instead of pretending to publish.
            {publisherMode() === "simulate" ? " Development simulation is enabled: you can mark a channel as simulated-connected to test the full flow." : " Set PUBLISHER_MODE=simulate in development to test the flow end to end."}
          </p>
          <div className="grid gap-4 md:grid-cols-2">
            {(await db.channelConnection.findMany({ where: { companyId: user.companyId } }))
              .sort((a, b) => PLATFORMS.indexOf(a.platform) - PLATFORMS.indexOf(b.platform))
              .map((c) => (
                <ChannelCard key={c.id} channel={{ platform: c.platform, accountName: c.accountName, status: c.connectionStatus, simulated: c.simulated, scopes: c.scopes, lastSync: c.lastSyncAt ? formatDateTime(c.lastSyncAt, tz) : null, lastError: c.lastError }} disabled={!editable} simulateAvailable={publisherMode() === "simulate"} />
              ))}
          </div>
        </>
      )}

      {tab === "posting" && (
        <div className="grid max-w-5xl grid-cols-1 gap-6 lg:grid-cols-[minmax(0,1.4fr)_minmax(0,1fr)]">
          <Card>
            <CardHeader title="Posting defaults" description={`Daily cadence and preferred publish times in ${tz}.`} />
            <div className="p-5"><PostingForm company={company} disabled={!editable} /></div>
          </Card>
          <Card>
            <CardHeader title="Daily AI drafts" description="The background job creates drafts once per day for the next day." />
            <div className="space-y-3 p-5 text-sm">
              <p>Status: <strong>{company.autoGenerateEnabled ? "On" : "Off"}</strong>{company.lastAutoGenerateDate && <> · last run for {company.lastAutoGenerateDate}</>}</p>
              <p className="text-muted">AI provider: {aiMode() === "mock" ? "simulated (development)" : `OpenAI (${process.env.OPENAI_MODEL || "gpt-5-mini"})${process.env.OPENAI_API_KEY ? "" : " — API key missing"}`}</p>
              {editable && <GenerateNowForm />}
            </div>
          </Card>
        </div>
      )}

      {tab === "users" && <UsersTab companyId={user.companyId} currentUserId={user.id} canManage={can(user.role, "users.manage")} tz={tz} />}

      {tab === "activity" && <ActivityTab companyId={user.companyId} tz={tz} />}
    </>
  );
}

async function UsersTab({ companyId, currentUserId, canManage, tz }: { companyId: string; currentUserId: string; canManage: boolean; tz: string }) {
  const users = await db.user.findMany({ where: { companyId }, orderBy: { createdAt: "asc" } });
  return (
    <div className="grid gap-6 grid-cols-1 xl:grid-cols-[minmax(0,1.6fr)_minmax(0,1fr)]">
      <Card>
        <CardHeader title="Team" description="Admin: everything. Manager: content, scheduling, settings. Creator: drafts. Approver: review and scheduling." />
        <div className="overflow-x-auto">
          <table className="w-full text-left text-sm">
            <thead className="text-xs text-muted"><tr className="border-b border-line"><th scope="col" className="px-5 py-2 font-medium">User</th><th scope="col" className="px-3 py-2 font-medium">Role</th><th scope="col" className="px-3 py-2 font-medium">Status</th><th scope="col" className="px-3 py-2 font-medium">Last sign-in</th><th scope="col" className="px-5 py-2"><span className="sr-only">Save</span></th></tr></thead>
            <tbody className="divide-y divide-line">
              {users.map((u) => (
                <UserRow key={u.id} user={{ id: u.id, name: u.name, email: u.email, role: u.role, status: u.status, lastLogin: u.lastLoginAt ? formatDateTime(u.lastLoginAt, tz) : "Never" }} canManage={canManage} isSelf={u.id === currentUserId} />
              ))}
            </tbody>
          </table>
        </div>
      </Card>
      {canManage && (
        <Card>
          <CardHeader title="Add a user" description="They sign in with this email and temporary password." />
          <div className="p-5"><CreateUserForm /></div>
        </Card>
      )}
    </div>
  );
}

async function ActivityTab({ companyId, tz }: { companyId: string; tz: string }) {
  const rows = await db.activityLog.findMany({ where: { companyId }, orderBy: { createdAt: "desc" }, take: 200 });
  return (
    <Card>
      <CardHeader title="Activity history" description="Latest 200 events: who did what, when, and the outcome." />
      <div className="overflow-x-auto">
        <table className="w-full text-left text-sm">
          <thead className="text-xs text-muted"><tr className="border-b border-line"><th scope="col" className="px-5 py-2 font-medium">Time ({tz})</th><th scope="col" className="px-3 py-2 font-medium">Actor</th><th scope="col" className="px-3 py-2 font-medium">Action</th><th scope="col" className="px-3 py-2 font-medium">Outcome</th><th scope="col" className="px-5 py-2 font-medium">Details</th></tr></thead>
          <tbody className="divide-y divide-line">
            {rows.length === 0 && <tr><td colSpan={5} className="px-5 py-6 text-center text-muted">No activity yet.</td></tr>}
            {rows.map((r) => (
              <tr key={r.id}>
                <td className="px-5 py-2 whitespace-nowrap text-muted">{formatDateTime(r.createdAt, tz)}</td>
                <td className="px-3 py-2">{r.actorName}</td>
                <td className="px-3 py-2">{r.entityType === "post" ? <Link className="text-brand-700 hover:underline" href={`/approvals?post=${r.entityId}`}>{r.action}</Link> : r.action}</td>
                <td className={cn("px-3 py-2", r.outcome === "failure" ? "font-medium text-red-700" : "text-emerald-800")}>{r.outcome === "failure" ? "Failed" : "Success"}</td>
                <td className="max-w-md px-5 py-2 break-words text-muted">{r.detail}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </Card>
  );
}
